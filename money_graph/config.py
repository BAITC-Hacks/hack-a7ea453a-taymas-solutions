"""Все пороги пайплайна в одном месте. README ссылается на эти константы.

Обоснования порогов — по распределению данных (2 248 узлов, июль 2026):
  in_deg:  p90=2, p95=3, p99=6, максимум 24;
  out_deg: p90=3, p95=5, p97=9, p98=14, максимум 116;
  медианный перевод 30 тыс. KZT, p75 — 81 тыс.
"""

# --- устройство выгрузки
MAX_DEPTH = 4                # глубина обхода: у узлов этого колена исходящие не выгружались
MIN_TX_KZT = 5_000           # порог выгрузки: переводы меньше этой суммы в данные не попали

# --- признаки
FAST_TRANSIT_DAYS = 2        # «пришло и ушло за 1–2 дня» — формулировка ТЗ
CYCLE_MAX_LEN = 5            # циклы длиной до 5: 468 штук, считаются за доли секунды
EXTERNAL_INFLOW_RATIO = 1.2  # out_kzt > 1.2 × in_kzt → у не-seed есть источник вне выгрузки

# --- роли (правила применяются по порядку, первое сработавшее побеждает)
# coordinator: собирает от многих И рассылает многим (p99 по входу, p97 по выходу)
COORD_MIN_PAYERS = 5
COORD_MIN_RECEIVERS = 10
# ... либо рассылает многим, собирает от нескольких и входит в направленный цикл
# длиной COORD_CYCLE_MIN_LEN..CYCLE_MAX_LEN; короткий цикл A⇄B его не отменяет.
COORD_CYCLE_MIN_PAYERS = 3
COORD_CYCLE_MIN_LEN = 3

# distributor: веер на ≥10 получателей (p97 = 9; ТЗ называет узлы с 60–116)
DISTR_MIN_RECEIVERS = 10

# consolidator: ≥3 уникальных плательщика (p95) или деньги от ≥2 разных seed —
# и видимый вход покрывает отток (не external_inflow_suspected): если отдано больше
# 1.2 × видимого входа, деньги пришли из-за пределов выгрузки и «сбор» их не объясняет
CONS_MIN_PAYERS = 3
CONS_MIN_SEED_PAYERS = 2

# transit: отдаёт дальше почти всё (ТЗ: 72 узла с pass_through 0.8–1.2) ...
TRANSIT_PT_LO, TRANSIT_PT_HI = 0.8, 1.2
# ... или меньшую долю, но быстро: ≥80% оттока ушло не позже 2 дней после поступления.
# Верхняя граница — та же, что у external_inflow_suspected: отдать больше 1.2 × видимого
# входа транзитный счёт не может, лишнее пришло из-за пределов выгрузки.
TRANSIT_WIDE_PT_LO, TRANSIT_WIDE_PT_HI = 0.5, EXTERNAL_INFLOW_RATIO
TRANSIT_WIDE_MIN_FAST_SHARE = 0.8
# seed транзитом не считается: его вход извне не виден, и по одному оттоку
# транзит не доказать — такие seed остаются peripheral с явной оговоркой в evidence

# terminal: исходящие наблюдаемы (depth < MAX_DEPTH) и узел удерживает ≥80% полученного
TERMINAL_MAX_PT = 0.2
# значимость: ≥100 тыс. KZT (верхний квартиль поступлений у узлов без оттока, p75=139 тыс.)
# или ≥2 плательщика, или ≥3 перевода — иначе это разовое поступление, т.е. peripheral
TERMINAL_MIN_KZT = 100_000
TERMINAL_MIN_PAYERS = 2
TERMINAL_MIN_TX = 3

EVIDENCE_MAX_LEN = 200
